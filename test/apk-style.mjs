import fs from 'node:fs';
import assert from 'node:assert/strict';
import JSZip from 'jszip';
import {JSDOM,VirtualConsole} from 'jsdom';
const apk=await JSZip.loadAsync(fs.readFileSync(process.argv[2]));
const css=await apk.file('assets/web/style.css').async('string');
const html=await apk.file('assets/web/index.html').async('string');
const errors=[];const virtualConsole=new VirtualConsole();virtualConsole.on('jsdomError',e=>errors.push(e));
const dom=new JSDOM(html,{virtualConsole});
const doc=dom.window.document;
const style=doc.createElement('style');style.textContent=css;doc.head.append(style);
assert.equal(errors.length,0,'The packaged stylesheet must parse; font URL semicolons must not leave trailing text.');
const viewport=doc.querySelector('meta[name="viewport"]').content;
assert.match(viewport,/(?:^|,)maximum-scale=1(?:,|$)/);
assert.match(viewport,/(?:^|,)user-scalable=no(?:,|$)/);
assert.match(css,/html, body, dialog\s*\{\s*touch-action:\s*pan-x pan-y;/);
const root=dom.window.getComputedStyle(doc.documentElement);
for(const [name,value] of [['--bg','#f0f2fb'],['--surface','#f9faff'],['--text','#20233b']])assert.equal(root.getPropertyValue(name).trim(),value,`Packaged ${name} must survive font import removal`);
assert.equal(dom.window.getComputedStyle(doc.querySelector('.reader-header')).backgroundColor,'rgb(249, 250, 255)');
assert.equal(doc.querySelector('symbol,use,.sprite'),null);
const wordmarkLight=doc.querySelector('.brand .brand-light');
const wordmarkDark=doc.querySelector('.brand .brand-dark');
assert.equal(dom.window.getComputedStyle(wordmarkLight).display,'block');
assert.equal(dom.window.getComputedStyle(wordmarkDark).display,'none');
const reader=doc.querySelector('#reader');reader.hidden=false;reader.classList.add('reading-fullscreen');
for(const selector of ['.reader-header','.reader-footer'])assert.equal(dom.window.getComputedStyle(doc.querySelector(selector)).display,'none');
doc.documentElement.classList.add('dark');reader.classList.remove('reading-fullscreen');
assert.equal(dom.window.getComputedStyle(wordmarkLight).display,'none');
assert.equal(dom.window.getComputedStyle(wordmarkDark).display,'block');
assert.equal(dom.window.getComputedStyle(doc.querySelector('.reader-header')).backgroundColor,'rgb(32, 35, 59)');
assert.doesNotMatch(css,/https?:\/\/fonts\./);
console.log('PASS: CSS extracted from signed APK parses, retains base theme colors, uses an opaque toolbar, and hides both toolbars in fullscreen.');
dom.window.close();
